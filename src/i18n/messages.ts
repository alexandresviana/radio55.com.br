const catalogs: Record<Exclude<Idioma, "pt">, Record<string, string>> = { es, en };

export function translate(
  idioma: Idioma,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const timeout = key.match(/^Servidor demorou a responder \(HTTP (\d+)\)\.( Tente de novo\.)?$/);
  if (timeout) {
    const templateKey = timeout[2]
      ? "Servidor demorou a responder (HTTP {status}). Tente de novo."
      : "Servidor demorou a responder (HTTP {status}).";
    return translate(idioma, templateKey, { status: timeout[1] });
  }

  const template = idioma === "pt" ? key : (catalogs[idioma][key] ?? key);
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`,
  );
}
